"""Build <team>_submission.zip with the exact structure required by the problem statement.

Required layout (authoritative, from the official problem statement):
    output/matching_results.tsv
    output/candidate_pairs.tsv
    code/business_entity_resolution/src/**/*.py
    code/business_entity_resolution/README.md
    code/business_entity_resolution/requirements.txt
    Documentation_template.md

Usage (from code/business_entity_resolution/):
    python scripts/make_zip.py --team <TEAM_NAME>

Reads output/matching_results.tsv and output/candidate_pairs.tsv from student_resource/output/
at build time (they are gitignored and regenerated by pipeline runs, so they must already exist).
Only src/, README.md and requirements.txt are copied from code/business_entity_resolution/ -- cache/,
tests/, notebooks/, __pycache__/ and .venv/ are intentionally excluded (not part of the required
layout, and cache/ in particular can be huge). After writing the zip, the script reopens it and
prints every member path so the layout can be eyeballed against the spec above.
"""
import argparse
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]  # student_resource/
PKG = ROOT / "code" / "business_entity_resolution"

REQUIRED_OUTPUT_FILES = ("matching_results.tsv", "candidate_pairs.tsv")
REQUIRED_PKG_FILES = ("README.md", "requirements.txt")
DOC_FILE = "Documentation_template.md"


def check_required_inputs(root=ROOT, pkg=PKG):
    """Raise FileNotFoundError with an actionable message if any required input is missing.

    Checks output/matching_results.tsv, output/candidate_pairs.tsv, code/business_entity_resolution/
    {README.md,requirements.txt,src/}, and Documentation_template.md. Returns nothing on success.
    """
    missing = []
    for name in REQUIRED_OUTPUT_FILES:
        if not (root / "output" / name).is_file():
            missing.append(str(root / "output" / name))
    for name in REQUIRED_PKG_FILES:
        if not (pkg / name).is_file():
            missing.append(str(pkg / name))
    if not (pkg / "src").is_dir():
        missing.append(str(pkg / "src"))
    if not (root / DOC_FILE).is_file():
        missing.append(str(root / DOC_FILE))
    if missing:
        joined = "\n  - ".join(missing)
        raise FileNotFoundError(
            "Cannot build submission zip, missing required file(s):\n  - " + joined +
            "\n\nRun the pipeline first (python -m src.run_pipeline --data ../../dataset "
            "--out ../../output) to produce output/matching_results.tsv and output/candidate_pairs.tsv, "
            "and make sure README.md, requirements.txt, src/ and Documentation_template.md are present."
        )


def build_zip(team, root=ROOT, pkg=PKG):
    """Write <team>_submission.zip under root and return its path.

    Assumes check_required_inputs() has already passed. Zips output/{matching_results.tsv,
    candidate_pairs.tsv}, every *.py under code/business_entity_resolution/src/ (recursively,
    which naturally excludes __pycache__/*.pyc), README.md, requirements.txt, and
    Documentation_template.md, in the layout required by the problem statement.
    """
    zip_path = root / f"{team}_submission.zip"
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as zf:
        for name in REQUIRED_OUTPUT_FILES:
            zf.write(root / "output" / name, f"output/{name}")
        src_root = pkg / "src"
        for p in sorted(src_root.rglob("*.py")):
            arcname = f"code/business_entity_resolution/src/{p.relative_to(src_root).as_posix()}"
            zf.write(p, arcname)
        for name in REQUIRED_PKG_FILES:
            zf.write(pkg / name, f"code/business_entity_resolution/{name}")
        zf.write(root / DOC_FILE, DOC_FILE)
    return zip_path


def expected_members(root=ROOT, pkg=PKG):
    """Return the set of arcnames build_zip() should have written, for self-verification."""
    members = {f"output/{name}" for name in REQUIRED_OUTPUT_FILES}
    src_root = pkg / "src"
    members |= {
        f"code/business_entity_resolution/src/{p.relative_to(src_root).as_posix()}"
        for p in src_root.rglob("*.py")
    }
    members |= {f"code/business_entity_resolution/{name}" for name in REQUIRED_PKG_FILES}
    members.add(DOC_FILE)
    return members


def verify_zip(zip_path, root=ROOT, pkg=PKG):
    """Reopen zip_path and assert its member set exactly matches expected_members().

    Returns the sorted list of member names (used for the printed listing). Raises AssertionError
    with the diff if the zip contains extra or missing entries -- guards against silently shipping
    an incomplete or polluted submission zip.
    """
    with zipfile.ZipFile(zip_path) as zf:
        actual = set(zf.namelist())
    expected = expected_members(root, pkg)
    if actual != expected:
        extra = sorted(actual - expected)
        missing = sorted(expected - actual)
        raise AssertionError(f"zip layout mismatch. extra={extra} missing={missing}")
    return sorted(actual)


def main(argv=None):
    """Parse --team, validate inputs, build the zip, verify its layout, and print the listing."""
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--team", required=True, help="Team name, used as <team>_submission.zip")
    args = ap.parse_args(argv)

    try:
        check_required_inputs(root=ROOT, pkg=PKG)
    except FileNotFoundError as exc:
        print(str(exc), file=sys.stderr)
        raise SystemExit(1)

    zip_path = build_zip(args.team, root=ROOT, pkg=PKG)
    members = verify_zip(zip_path, root=ROOT, pkg=PKG)
    for name in members:
        print(name)
    print(f"-> {zip_path} ({zip_path.stat().st_size / 1e6:.2f} MB)")


if __name__ == "__main__":
    main()
